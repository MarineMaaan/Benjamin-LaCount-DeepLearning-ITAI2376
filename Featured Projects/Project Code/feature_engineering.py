print(test_df['FareBand'].value_counts())

"""## Encode categorical variables

### Subtask:
Use one-hot encoding for 'Sex', 'Embarked', and 'Title'.

**Reasoning**:
Select the columns for one-hot encoding, apply one-hot encoding, concatenate the new columns, and drop the original columns. Finally, display the heads of the modified dataframes.
"""

# Select columns for one-hot encoding
cols_to_encode = ['Sex', 'Embarked', 'Title']

# Apply one-hot encoding
train_encoded = pd.get_dummies(train_df[cols_to_encode], prefix=cols_to_encode)
test_encoded = pd.get_dummies(test_df[cols_to_encode], prefix=cols_to_encode)

# Align columns - this is crucial to ensure both dataframes have the same columns
train_encoded, test_encoded = train_encoded.align(test_encoded, join='outer', axis=1, fill_value=0)


# Concatenate encoded columns with original dataframes and drop original columns
train_df = pd.concat([train_df.drop(cols_to_encode, axis=1), train_encoded], axis=1)
test_df = pd.concat([test_df.drop(cols_to_encode, axis=1), test_encoded], axis=1)

# Display the head of the modified dataframes
print("Train DataFrame after one-hot encoding:")
display(train_df.head())
print("\nTest DataFrame after one-hot encoding:")
display(test_df.head())

"""## Prepare data for modeling

### Subtask:
Separate features and target variable for the training data and ensure consistency between training and testing data after feature engineering and encoding.

**Reasoning**:
Separate the target variable and features for the training data and select the relevant features for both training and testing datasets, then align the columns.
"""

# Define the target variable for the training data
y_train = train_df['Survived']

# Define the features for the training data, dropping irrelevant columns
X_train = train_df.drop(['Survived', 'PassengerId', 'Name', 'Ticket', 'Cabin', 'AgeBand', 'FareBand', 'SibSp', 'Parch'], axis=1)

# Define the features for the testing data, dropping the same irrelevant columns
X_test = test_df.drop(['PassengerId', 'Name', 'Ticket', 'Cabin', 'AgeBand', 'FareBand', 'SibSp', 'Parch'], axis=1)

# Align the columns of X_train and X_test to ensure consistency
X_train, X_test = X_train.align(X_test, join='inner', axis=1)

# Display the head of the resulting feature and target dataframes
print("X_train head:")
display(X_train.head())
print("\ny_train head:")
display(y_train.head())
print("\nX_test head:")
display(X_test.head())

"""## Train and compare models

### Subtask:
Train a Logistic Regression model on the original features, train a Logistic Regression model on the engineered features, and compare the accuracy of the two models.

**Reasoning**:
Train Logistic Regression models on both original and engineered features and compare their accuracy on the training data.
"""

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

# Create a copy of the original training and testing dataframes before feature engineering and encoding
train_df_original = pd.read_csv('/content/train.csv')
test_df_original = pd.read_csv('/content/test.csv')

# Handle missing values in the original dataframes as done previously
median_age_original = train_df_original['Age'].median()
train_df_original['Age'] = train_df_original['Age'].fillna(median_age_original)
test_df_original['Age'] = test_df_original['Age'].fillna(median_age_original)
most_frequent_embarked_original = train_df_original['Embarked'].mode()[0]
train_df_original['Embarked'] = train_df_original['Embarked'].fillna(most_frequent_embarked_original)
median_fare_test_original = test_df_original['Fare'].median()
test_df_original['Fare'] = test_df_original['Fare'].fillna(median_fare_test_original)

# Define features and target for original data
# Drop the same irrelevant columns except for 'Sex', 'Embarked', and 'Title' which are kept as original
X_train_original = train_df_original.drop(['Survived', 'PassengerId', 'Name', 'Ticket', 'Cabin'], axis=1)
y_train_original = train_df_original['Survived']
X_test_original = test_df_original.drop(['PassengerId', 'Name', 'Ticket', 'Cabin'], axis=1)


# One-hot encode categorical features in the original dataframes for modeling
cols_to_encode_original = ['Sex', 'Embarked'] # Title is not in original dataframes, it was engineered
X_train_original = pd.get_dummies(X_train_original, columns=cols_to_encode_original, drop_first=True)
X_test_original = pd.get_dummies(X_test_original, columns=cols_to_encode_original, drop_first=True)

# Align columns after one-hot encoding
X_train_original, X_test_original = X_train_original.align(X_test_original, join='inner', axis=1)


# Train Logistic Regression model on original features
model_original = LogisticRegression(solver='liblinear')
model_original.fit(X_train_original, y_train_original)

# Make predictions on the training data using the original features model
y_pred_original = model_original.predict(X_train_original)

# Train Logistic Regression model on engineered features
# X_train and y_train are already prepared from previous steps
model_engineered = LogisticRegression(solver='liblinear')
model_engineered.fit(X_train, y_train)

# Make predictions on the training data using the engineered features model
y_pred_engineered = model_engineered.predict(X_train)

# Calculate accuracy for both models on the training data
accuracy_original = accuracy_score(y_train_original, y_pred_original)
accuracy_engineered = accuracy_score(y_train, y_pred_engineered)

# Print the accuracy scores
print(f"Accuracy of Logistic Regression on Original Features (Training Data): {accuracy_original:.4f}")
print(f"Accuracy of Logistic Regression on Engineered Features (Training Data): {accuracy_engineered:.4f}")