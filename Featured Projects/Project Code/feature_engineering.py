"""## Handle missing values

### Subtask:
Impute missing 'Age' values with the median and fill missing 'Embarked' values with the most frequent category in the training data.

**Reasoning**:
Impute missing 'Age' values with the median and fill missing 'Embarked' values with the most frequent category in the training data. Also, fill the missing 'Fare' value in the test data.
"""

# Calculate the median of the 'Age' column in the train_df DataFrame.
median_age = train_df['Age'].median()

# Fill the missing values in the 'Age' column of both train_df and test_df DataFrames with the calculated median.
train_df['Age'] = train_df['Age'].fillna(median_age)
test_df['Age'] = test_df['Age'].fillna(median_age)

# Calculate the most frequent value (mode) of the 'Embarked' column in the train_df DataFrame.
most_frequent_embarked = train_df['Embarked'].mode()[0]

# Fill the missing values in the 'Embarked' column of the train_df DataFrame with the calculated mode.
train_df['Embarked'] = train_df['Embarked'].fillna(most_frequent_embarked)

# Fill the single missing 'Fare' value in the test_df with the median 'Fare' from the train_df.
median_fare_train = train_df['Fare'].median()
test_df['Fare'] = test_df['Fare'].fillna(median_fare_train)

print("Missing values after imputation in train_df:")
print(train_df.isnull().sum())

print("\nMissing values after imputation in test_df:")
print(test_df.isnull().sum())

"""## Create new features

### Subtask:
Create 'FamilySize' and 'IsAlone' features, extract 'Title' from the 'Name' column, bin 'Age' into categories, and convert 'Fare' into quartiles.

**Reasoning**:
Implement all the feature engineering steps: create FamilySize and IsAlone features, extract and process the Title, bin Age into categories, and convert Fare into quartiles.
"""

# 1. Create 'FamilySize' column
train_df['FamilySize'] = train_df['SibSp'] + train_df['Parch'] + 1
test_df['FamilySize'] = test_df['SibSp'] + test_df['Parch'] + 1

# 2. Create 'IsAlone' column
train_df['IsAlone'] = 1
test_df['IsAlone'] = 1
train_df.loc[train_df['FamilySize'] > 1, 'IsAlone'] = 0
test_df.loc[test_df['FamilySize'] > 1, 'IsAlone'] = 0

# 3. Extract 'Title' from 'Name'
train_df['Title'] = train_df['Name'].str.extract(r' ([A-Za-z]+)\.', expand=False)
test_df['Title'] = test_df['Name'].str.extract(r' ([A-Za-z]+)\.', expand=False)

# 4. Replace less frequent titles with 'Rare'
for df in [train_df, test_df]:
    df['Title'] = df['Title'].replace(['Lady', 'Countess', 'Capt', 'Col', 'Don', 'Dr', 'Major', 'Rev', 'Sir', 'Jonkheer', 'Dona'], 'Rare')
    df['Title'] = df['Title'].replace('Mlle', 'Miss')
    df['Title'] = df['Title'].replace('Ms', 'Miss')
    df['Title'] = df['Title'].replace('Mme', 'Mrs')

# 5. Bin 'Age' into categories
train_df['AgeBand'] = pd.cut(train_df['Age'], 5)
test_df['AgeBand'] = pd.cut(test_df['Age'], 5)

# 6. Create 'FareBand' by converting 'Fare' into quartiles
test_df['Fare'] = test_df['Fare'].fillna(test_df['Fare'].median()) # Ensure no missing values in Fare before qcut
train_df['FareBand'] = pd.qcut(train_df['Fare'], 4)
test_df['FareBand'] = pd.qcut(test_df['Fare'], 4)


print("Train DataFrame after feature engineering:")
display(train_df.head())
print("\nTest DataFrame after feature engineering:")
display(test_df.head())
print("\nTrain DataFrame 'Title' distribution:")
print(train_df['Title'].value_counts())
print("\nTest DataFrame 'Title' distribution:")
print(test_df['Title'].value_counts())
print("\nTrain DataFrame 'AgeBand' distribution:")
print(train_df['AgeBand'].value_counts())
print("\nTest DataFrame 'AgeBand' distribution:")
print(test_df['AgeBand'].value_counts())
print("\nTrain DataFrame 'FareBand' distribution:")
print(train_df['FareBand'].value_counts())
